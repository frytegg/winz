// @ts-check
import { lineOf } from '../../lib/text.mjs';

/**
 * SL-T09 static: a badge above the headline. Within the 10 lines above an <h1> (FD14-F10's verified window): a
 * shadcn <Badge>, a pill (rounded-full with small x and y padding, not a sized avatar or dot, class names order-free),
 * a class named badge, pill, chip, eyebrow or kicker, or a small-caps eyebrow (uppercase with wide tracking; FD10 S09,
 * Krebs's small-caps shape). Not counted (registry and FD10-F26): a badge that is a link or carries data-proof (a
 * checkable status), buttons, breadcrumbs and navigation, comments.
 *
 * @typedef {import('../load.mjs').StaticContext} StaticContext
 * @typedef {import('../load.mjs').SourceFile} SourceFile
 * @typedef {import('../load.mjs').StaticFinding} StaticFinding
 */

const RULE = 'SL-T09';
const LINES_ABOVE = 10;
const H1 = /<h1(?=[\s>])/g;
const PILL_X = /^px-(?:2|2\.5|3|3\.5|4|5)$/;
const PILL_Y = /^py-(?:0\.5|1|1\.5|2)$/;
const SIZED = /^(?:w|h|size)-(?:\d{2,}|\[)/;
const NAMED = /^(?:badge|pill|chip|eyebrow|kicker|tagline-pill|hero-badge|hero-pill|announcement)(?:$|[-_])/i;
const TRACKING = /^tracking-(?:wide|wider|widest|\[[\d.]+(?:em|px|rem)\])$/;
const EXEMPT_TAG = /^(?:a|Link|NavLink|NextLink|button|Button|nav|li|ol|Breadcrumb\w*)$/;
const BREADCRUMB = /aria-label\s*=\s*['"{]*breadcrumb|<Breadcrumb\b|\bbreadcrumbs?\b/i;

/**
 * @param {StaticContext} ctx
 * @returns {StaticFinding[]}
 */
export function detect(ctx) {
  /** @type {StaticFinding[]} */
  const out = [];
  for (const file of shippedFiles(ctx)) {
    if (file.kind === 'css' || file.kind === 'json') continue;
    const code = file.code;
    const contexts = classContexts(file);
    for (const h1 of code.matchAll(H1)) {
      const from = lineStart(code, h1.index, LINES_ABOVE);
      const window = code.slice(from, h1.index);
      if (BREADCRUMB.test(window)) continue;
      const candidates = [];
      for (const m of window.matchAll(/<Badge(?=[\s>])/g)) candidates.push({ index: from + m.index, shape: 'shadcn <Badge>' });
      for (const c of contexts) {
        if (c.index < from || c.index >= h1.index) continue;
        const shape = badgeShape(c.text);
        if (shape) candidates.push({ index: c.index, shape });
      }
      const nearest = candidates
        .filter((c) => !isExempt(code, c.index))
        .sort((a, b) => b.index - a.index)[0];
      if (nearest) {
        const lines = lineOf(code, h1.index) - lineOf(code, nearest.index);
        out.push(finding(file, nearest.index, nearest.shape, `${nearest.shape} ${lines} line${lines === 1 ? '' : 's'} above the <h1>`));
      }
    }
  }
  return unique(out);
}

/**
 * The badge shape of a class list, or null: a pill, a named badge class, or an uppercase tracked eyebrow.
 * @param {string} text
 * @returns {string | null}
 */
function badgeShape(text) {
  const names = utilities(text).filter(atRest).map((u) => u.utility);
  if (names.includes('rounded-full') && names.some((u) => PILL_X.test(u)) && names.some((u) => PILL_Y.test(u)) && !names.some((u) => SIZED.test(u))) {
    return 'pill badge';
  }
  if (names.some((u) => NAMED.test(u))) return 'badge class';
  if (names.includes('uppercase') && names.some((u) => TRACKING.test(u))) return 'uppercase tracked eyebrow';
  return null;
}

/**
 * True when the badge is a link, a button, inside navigation, or carries data-proof or an href (a checkable status).
 * @param {string} code
 * @param {number} index
 * @returns {boolean}
 */
function isExempt(code, index) {
  const tag = code.startsWith('<Badge', index) ? { name: 'Badge', start: index } : tagAt(code, index);
  if (!tag) return false;
  if (EXEMPT_TAG.test(tag.name)) return true;
  const end = openTagEnd(code, tag.start);
  const open = code.slice(tag.start, end < 0 ? tag.start + 400 : end);
  if (/\b(?:href|data-proof)\s*=/.test(open)) return true;
  const before = code.slice(Math.max(0, tag.start - 200), tag.start);
  return /<(?:a|Link|NextLink)\b[^<>]*>\s*$/.test(before);
}

/**
 * The offset of the line `count` lines above the line holding `index`.
 * @param {string} code
 * @param {number} index
 * @param {number} count
 * @returns {number}
 */
function lineStart(code, index, count) {
  let at = code.lastIndexOf('\n', index - 1);
  for (let i = 0; i < count && at > 0; i += 1) at = code.lastIndexOf('\n', at - 1);
  return at + 1;
}

// ─── shared:files ───
/**
 * Test, spec and story files, test folders, type declarations and the repository's own scripts/ and tools/ folders
 * never reach the judged page.
 */
const NOT_SHIPPED = /(?:^|\/)(?:__tests__|__mocks__|__fixtures__|__stories__|tests?|e2e|cypress|playwright|stories|\.storybook)\/|^(?:scripts|tools)\/|\.(?:test|spec|stories|story|cy|e2e)\.[cm]?[jt]sx?$|\.d\.[cm]?ts$/i;
/** shadcn and Figma Make primitives: library code, judged through the files that use it. */
const LIBRARY = /(?:^|\/)components\/(?:ui|figma)\//i;
/** A CSS comment inside one template literal (CSS-in-JS): it never crosses a backtick. */
const TEMPLATE_CSS_COMMENT = /\/\*(?:(?!\*\/)[^`])*\*\//g;

/**
 * The files a detector reads: shipped sources only, never precompiled Tailwind output (it repeats its source,
 * FD14-F23), and library primitives only when asked. Their code also has the CSS comments of CSS-in-JS template
 * literals blanked (string content to the JavaScript comment stripper), same length and lines: comments never count.
 * @param {StaticContext} ctx
 * @param {{library?: boolean}} [options]
 * @returns {SourceFile[]}
 */
function shippedFiles(ctx, { library = false } = {}) {
  return ctx.files
    .filter((f) => !NOT_SHIPPED.test(f.path) && (library || !LIBRARY.test(f.path)) && !f.text.slice(0, 600).includes('/*! tailwindcss v'))
    .map((f) => (f.kind === 'css' || f.kind === 'json' || !f.code.includes('/*')
      ? f
      : { ...f, code: f.code.replace(TEMPLATE_CSS_COMMENT, (m) => m.replace(/[^\n]/g, ' ')) }));
}
