def setUpModule() -> None:
    """Isolate git from the user's global/system configuration."""
    global _GIT_HOME
    _GIT_HOME = tempfile.mkdtemp(prefix="harden-gitcfg-")
    cfg = Path(_GIT_HOME) / "gitconfig"
    cfg.write_text("[user]\n\tname = Harden Test\n\temail = harden@example.invalid\n"
                   "[init]\n\tdefaultBranch = main\n[commit]\n\tgpgsign = false\n"
                   "[core]\n\tautocrlf = false\n", encoding="utf-8")
    values = {"GIT_CONFIG_GLOBAL": str(cfg), "GIT_CONFIG_NOSYSTEM": "1",
              "GIT_AUTHOR_NAME": "Harden Test", "GIT_AUTHOR_EMAIL": "harden@example.invalid",
              "GIT_COMMITTER_NAME": "Harden Test", "GIT_COMMITTER_EMAIL": "harden@example.invalid"}
    for key, value in values.items():
        _SAVED_ENV[key] = os.environ.get(key)
        os.environ[key] = value


def tearDownModule() -> None:
    for key, value in _SAVED_ENV.items():
        if value is None:
            os.environ.pop(key, None)
        else:
            os.environ[key] = value
    if _GIT_HOME:
        _rmtree(_GIT_HOME)


def _rmtree(path: str) -> None:
    def fix(func, target, _exc):  # type: ignore[no-untyped-def]
        os.chmod(target, stat.S_IWRITE)
        func(target)
    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=fix)
    else:
        shutil.rmtree(path, onerror=fix)


def _git(repo: Path, *args: str) -> str:
    proc = subprocess.run(["git", *args], cwd=str(repo), stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"git {args} failed: {proc.stderr.decode(errors='replace')}")
    return proc.stdout.decode("utf-8", errors="replace")


def _write(repo: Path, rel: str, text: str) -> None:
    target = repo / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")


def lines(n: int, prefix: str = "x") -> str:
    return "".join("{}{} = {}\n".format(prefix, i, i) for i in range(n))


IN_SCOPE = ["README.md", "config.yaml", "src/app.py", "src/util.py", "tests/test_app.py"]


class LedgerCase(unittest.TestCase):
    def setUp(self) -> None:
        self.repo = Path(tempfile.mkdtemp(prefix="harden-ledger-"))
        _git(self.repo, "init", "-q")
        _write(self.repo, "src/app.py", lines(10))
        _write(self.repo, "src/util.py", lines(4))
        _write(self.repo, "tests/test_app.py", "def test_x():\n\n    assert True\n")
        _write(self.repo, "README.md", "# demo\nusage\n")
        _write(self.repo, "config.yaml", "a: 1\n")
        _write(self.repo, "package-lock.json", "{}\n")
        _write(self.repo, "dist/bundle.js", "var a;\n")
        _write(self.repo, "vendor/lib.js", "var b;\n")
        _write(self.repo, "db/migrations/0001_init.sql", "create table t (id int);\n")
        _write(self.repo, "src/__snapshots__/app.snap", "snap\n")
        _write(self.repo, "src/gen_pb.py", "# Code generated by protoc. DO NOT EDIT.\nx = 1\n")
        (self.repo / "assets").mkdir()
        (self.repo / "assets" / "logo.bin").write_bytes(b"\x89PNG\x00\x01\x02")
        _git(self.repo, "add", "-A")
        _git(self.repo, "commit", "-q", "-m", "init")

    def tearDown(self) -> None:
        _rmtree(str(self.repo))

    def lg(self, *args: str) -> Tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                code = lg.main(list(args) + ["--repo", str(self.repo)])
            except SystemExit as exc:
                code = exc.code if isinstance(exc.code, int) else 2
        return code, out.getvalue(), err.getvalue()

    def ledger(self) -> Dict[str, Any]:
        return json.loads((self.repo / lg.LEDGER_REL).read_text(encoding="utf-8"))

    def init(self, *extra: str) -> None:
        code, _, err = self.lg("init", *extra)
        self.assertEqual(code, 0, err)

    def record(self, lens: str, number: int, files: List[str], candidates: int = 0,
               *extra: str) -> Tuple[int, str, str]:
        return self.lg("record", "--lens", lens, "--pass", str(number), "--model", "m-1",
                       "--effort", "high", "--prompt-hash", HASH, "--classes", "c1",
                       "--candidates", str(candidates), "--files", *files, *extra)

    def check_json(self, *extra: str) -> Tuple[int, Dict[str, Any]]:
        code, out, err = self.lg("check", "--json", *extra)
        self.assertIn(code, (0, 1), err)
        return code, json.loads(out)

    def write_findings(self, rel: str, findings: List[Dict[str, Any]]) -> None:
        _write(self.repo, rel, json.dumps({"version": 1, "base_sha": "abcdef1",
                                           "generated": "2026-09-24T00:00:00Z",
                                           "tool_versions": {}, "findings": findings}))


