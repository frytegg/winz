class AutonomousBudgetTests(LedgerCase):
    """DT-25 in autonomous mode: the cap is the profile's budget.max_tokens, and a profile
    without one (the documented default) means no cap, recorded rather than warned about."""

    def write_marker(self, mode: Optional[str] = "auto", max_tokens: Optional[int] = None,
                     **extra: Any) -> None:
        marker: Dict[str, Any] = {"base_sha": "0" * 40, "branch": "harden/test",
                                  "profile": {"present": True, "valid": True, "effective": {
                                      "budget": {"max_tokens": max_tokens,
                                                 "deadline_utc": None}}}}
        if mode is not None:
            marker["mode"] = mode
        marker.update(extra)
        _write(self.repo, ".harden/active", json.dumps(marker))

    def cap_warnings(self) -> List[str]:
        _code, data = self.check_json("--lenses", "security")
        return [w for w in data["warnings"] if "budget" in w]

    def test_no_cap_is_the_autonomous_default(self) -> None:
        self.write_marker()
        code, out, err = self.lg("init")
        self.assertEqual(code, 0, err)
        self.assertIn("budget cap: no cap (autonomous default)", out)
        self.assertNotIn("--cap N", out)
        budget = self.ledger()["budget"]
        self.assertIsNone(budget["budget_cap_tokens"])
        self.assertEqual(budget["budget_cap_note"], lg.AUTONOMOUS_NO_CAP)
        _code, data = self.check_json("--lenses", "security")
        self.assertEqual(data["budget"]["budget_cap_note"], "no cap (autonomous default)")
        lacks = [w for w in data["warnings"] if "lacks" in w]
        self.assertEqual(len(lacks), 1)
        self.assertNotIn("budget_cap_tokens", lacks[0])
        self.assertIn("estimate_tokens, verification_reserve", lacks[0])
        _code, text, _err = self.lg("check", "--lenses", "security")
        self.assertIn("cap no cap (autonomous default)", text)
        # A report-only run that started autonomous takes the same default.
        self.write_marker(mode="report-only", mode_requested="auto")
        self.assertFalse(any("lacks budget_cap_tokens" in w for w in self.cap_warnings()))
        # After run_state.py stop the marker is gone; the header still says so.
        (self.repo / ".harden" / "active").unlink()
        self.assertFalse(any("budget_cap_tokens" in w for w in self.cap_warnings()))
        # A cap the agent picked itself is flagged: the default is no cap.
        self.write_marker()
        self.assertEqual(self.lg("budget", "--cap", "5000")[0], 0)
        self.assertIsNone(self.ledger()["budget"]["budget_cap_note"])
        self.assertTrue(any("never chooses a cap itself" in w for w in self.cap_warnings()))

    def test_profile_cap_is_taken_and_checked(self) -> None:
        self.write_marker(max_tokens=4000000)
        code, out, err = self.lg("init")
        self.assertEqual(code, 0, err)
        budget = self.ledger()["budget"]
        self.assertEqual(budget["budget_cap_tokens"], 4000000)
        self.assertIn("budget.max_tokens", budget["budget_cap_note"])
        self.assertIn("4000000 tokens", out)
        self.assertFalse(any("budget_cap_tokens" in w for w in self.cap_warnings()))
        self.assertEqual(self.lg("budget", "--cap", "100")[0], 0)
        self.assertTrue(any("budget.max_tokens is 4000000" in w for w in self.cap_warnings()))
        # --budget-cap given explicitly still wins at init (and is then checked).
        self.init("--force", "--budget-cap", "4000000")
        self.assertFalse(any("budget_cap_tokens" in w for w in self.cap_warnings()))

    def test_the_cap_stays_required_outside_autonomous_mode(self) -> None:
        for mode, extra in (("interactive", {}), ("apply", {}),
                            ("report-only", {"mode_requested": "interactive"}), (None, {})):
            with self.subTest(mode=mode, extra=extra):
                self.write_marker(mode=mode, **extra)
                self.init("--force")
                self.assertIsNone(self.ledger()["budget"]["budget_cap_note"])
                self.assertTrue(any("lacks budget_cap_tokens" in w
                                    for w in self.cap_warnings()))
        (self.repo / ".harden" / "active").unlink()
        self.init("--force")
        self.assertTrue(any("lacks budget_cap_tokens" in w for w in self.cap_warnings()))
        self.assertEqual(lg.cap_policy(None), (False, None))
        self.assertEqual(lg.cap_policy({"mode": "auto", "profile": {"effective": {
            "budget": {"max_tokens": True}}}}), (True, None))


class NotebookBudgetTests(LedgerCase):
    """DT-25 read-token estimates for notebooks, and the per-pass overhead."""

    def test_notebook_tokens_come_from_code_cells_or_bytes(self) -> None:
        image = "iVBORw0KGgo" + "A" * 60000
        notebook = {"cells": [
            {"cell_type": "markdown", "source": ["# Title\n", "text\n"]},
            {"cell_type": "code", "source": ["import numpy as np\n", "\n", "x = np.arange(3)\n"],
             "outputs": [{"output_type": "display_data", "data": {"image/png": image}}]},
            {"cell_type": "code", "source": "y = x * 2\nprint(y)\n", "outputs": []},
        ], "metadata": {}, "nbformat": 4, "nbformat_minor": 5}
        _write(self.repo, "nb/analysis.ipynb", json.dumps(notebook, indent=1))
        broken = '{"cells": [' + "x" * 4000
        _write(self.repo, "nb/broken.ipynb", broken)
        _git(self.repo, "add", "-A")
        _git(self.repo, "commit", "-q", "-m", "notebooks")
        self.init()
        data = self.ledger()
        rows = {f["path"]: f for f in data["files"]}
        good = rows["nb/analysis.ipynb"]
        self.assertEqual(good["loc"], 4)                       # code-cell lines only
        self.assertEqual(good["est_tokens"], int(round(8.3 * 4)))
        self.assertEqual(good["tokens_basis"], "8.3 x notebook code-cell LOC")
        bad = rows["nb/broken.ipynb"]
        self.assertEqual(bad["est_tokens"], -(-len(broken.encode("utf-8")) // 4))
        self.assertTrue(bad["tokens_basis"].startswith("bytes/4"))
        unit = next(u for u in data["units"] if u["id"] == "nb/broken.ipynb")
        self.assertEqual(unit["est_tokens"], bad["est_tokens"])
        plain = sum(f["loc"] for f in data["files"] if f["path"] != "nb/broken.ipynb")
        self.assertEqual(data["budget"]["full_read_tokens"],
                         int(round(8.3 * plain)) + bad["est_tokens"])

    def test_pass_overhead_is_recorded_and_reported(self) -> None:
        self.init()
        code, out, _ = self.lg("budget", "--pass-overhead", "12000")
        self.assertEqual(code, 0)
        self.assertEqual(self.ledger()["budget"]["pass_overhead_tokens"], 12000)
        self.record("security", 1, ["src/app.py"])
        _, data = self.check_json("--lenses", "security")
        self.assertEqual(data["budget"]["pass_overhead_tokens"], 12000)
        self.assertEqual(data["budget"]["pass_overhead_so_far"], 12000)
        self.assertEqual(self.lg("budget", "--pass-overhead", "-1")[0], 2)

    def test_help_documents_file_ranges_and_map_format(self) -> None:
        parser = lg.build_parser()
        actions = {a.dest: a for a in parser._subparsers._actions  # type: ignore[union-attr]
                   if isinstance(a, lg.argparse._SubParsersAction)}
        subs = actions["command"].choices
        record_help = subs["record"].format_help()
        self.assertIn("PATH:START-END", record_help)
        self.assertIn('"ranges"', record_help)
        merge_help = subs["merge"].format_help()
        self.assertIn('"passes"', merge_help)
        self.assertIn('"source": "prescan"', merge_help)


