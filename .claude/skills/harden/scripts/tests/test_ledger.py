class ExclusionTests(unittest.TestCase):
    def setUp(self) -> None:
        self.repo = Path(tempfile.mkdtemp(prefix="harden-ledger-ex-"))
        self.addCleanup(_rmtree, str(self.repo))
        _git(self.repo, "init", "-q")

    def lg(self, *args: str) -> Tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = lg.main(list(args) + ["--repo", str(self.repo)])
        return code, out.getvalue(), err.getvalue()

    def commit_and_init(self) -> Dict[str, Any]:
        _git(self.repo, "add", "-A")
        _git(self.repo, "commit", "-q", "-m", "x")
        code, out, err = self.lg("init")
        self.assertEqual(code, 0, out + err)
        return json.loads((self.repo / lg.LEDGER_REL).read_text(encoding="utf-8"))

    def test_yarn_tool_files_and_pnp_are_excluded(self) -> None:
        for rel in (".yarn/releases/yarn-3.6.4.cjs", ".yarn/plugins/@yarnpkg/plugin-typescript.cjs",
                    ".yarn/sdks/typescript/lib/tsc.js", ".pnp.cjs", ".yarn/patches/foo.patch",
                    ".yarnrc.yml", "src/a.ts"):
            _write(self.repo, rel, "x = 1\n")
        data = self.commit_and_init()
        reasons = {e["path"]: e["reason"] for e in data["exclusions"]}
        for rel in (".yarn/releases/yarn-3.6.4.cjs", ".yarn/plugins/@yarnpkg/plugin-typescript.cjs",
                    ".yarn/sdks/typescript/lib/tsc.js", ".pnp.cjs"):
            self.assertIn("Yarn", reasons.get(rel, ""), rel)
        paths = {f["path"] for f in data["files"]}
        self.assertTrue({".yarn/patches/foo.patch", ".yarnrc.yml", "src/a.ts"} <= paths, paths)

    def test_files_over_one_megabyte_are_excluded(self) -> None:
        line = "a = 1\n"
        big = line * (1000001 // len(line) + 1)
        (self.repo / "big.txt").write_bytes(big[:1000001].encode("utf-8"))
        (self.repo / "ok.txt").write_bytes(big[:999999].encode("utf-8"))
        data = self.commit_and_init()
        reasons = {e["path"]: e["reason"] for e in data["exclusions"]}
        self.assertTrue(reasons["big.txt"].startswith("file over 1,000,000 bytes"))
        self.assertIn("ok.txt", {f["path"] for f in data["files"]})

    def test_long_line_files_are_estimated_from_bytes(self) -> None:
        (self.repo / "long.txt").write_bytes((("x" * 4000 + "\n") * 10).encode("utf-8"))
        data = self.commit_and_init()
        row = next(f for f in data["files"] if f["path"] == "long.txt")
        self.assertEqual(row["est_tokens"], -(-40010 // 4))
        self.assertEqual(row["tokens_basis"], "bytes/4 (long lines)")



