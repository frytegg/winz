def gaming(report: dg.Report) -> List[Dict[str, object]]:
    return [i for i in report.soft if i["kind"] == "test_gaming"]


def gaming_keys(report: dg.Report) -> Set[Tuple[str, str, str]]:
    """(category, file, pattern) of every test_gaming item."""
    return {(str(i["category"]), str(i.get("file", "")), str(i.get("pattern", "")))
            for i in gaming(report)}


