    def test_added_markers_are_hard(self) -> None:
        self.repo.write("tests/test_app.py", self.BASE + "\n\n@pytest.mark.skip\ndef test_later():\n"
                        "    assert 1\n")
        report = self.guard()
        self.assertIn(("marker_added", "tests/test_app.py"), items(report, "hard"))
        codes = {p["code"] for i in self.hard_tests(report) for p in i["problems"]}
        self.assertIn("skip-marker", codes)
        js = "import { it, expect } from 'vitest';\n\nit('a', () => {\n  expect(1).toBe(1);\n});\n"
        self.repo.write("tests/a.test.ts", js)
        self.repo.write("tests/it.rs", "#[test]\nfn adds() {\n    assert_eq!(1 + 1, 2);\n}\n")
        self.repo.write("tests/test_app.py", self.BASE)
        self.rebase_on("js and rust tests")
        for path, text in (("tests/a.test.ts", js + "\nit.skip('b', () => {});\n"),
                           ("tests/a.test.ts", js + "\ntest.only('b', () => {});\n"),
                           ("tests/it.rs", "#[test]\nfn adds() {\n    assert_eq!(1 + 1, 2);\n}\n"
                            "\n#[test]\n#[ignore]\nfn later() {}\n")):
            with self.subTest(text=text[-30:]):
                self.repo.write(path, text)
                report = self.guard()
                self.assertIn(("marker_added", path), items(report, "hard"))
                codes = {p["code"] for i in self.hard_tests(report) for p in i["problems"]}
                self.assertIn("skip-marker", codes)
                self.repo.git("checkout", "--", path)

