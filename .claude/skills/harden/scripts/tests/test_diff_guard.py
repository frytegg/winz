class StrengthenGuardTests(unittest.TestCase):
    """Existing tests only gain checked additions (protocol-change PC-06; U01-F07)."""

    APPEND = "    assert add(2, 2) == 4\n"
    BASE = "from src.app import add\n\n\ndef test_add():\n    assert add(1, 2) == 3\n"

    def setUp(self) -> None:
        self.repo, self.base = make_repo()

    def tearDown(self) -> None:
        self.repo.cleanup()

    def guard(self, quick: bool = False, base: Optional[str] = None) -> dg.Report:
        cfg = dg.load_run_config(self.repo.path)
        return dg.run_guard(self.repo.path, base or self.base, cfg, quick=quick)

    def hard_tests(self, report: dg.Report, reason: Optional[str] = None) -> List[Dict]:
        return [i for i in report.hard if i["kind"] in ("test_modified", "test_deleted")
                and (reason is None or i.get("reason") == reason)]

    def rebase_on(self, message: str) -> str:
        base = self.repo.commit(message)
        self.repo.write_active(base)
        self.base = base
        return base

    def test_pilot3_tail_append_under_old_inventory_globs_is_listed_not_hard(self) -> None:
        """pilot-auto-calibration A01-F53: a marker whose protected list holds the test globs."""
        here = str(Path(__file__).resolve().parent)
        if here not in sys.path:
            sys.path.insert(0, here)
        import test_hook_guard as TH
        self.repo.write("tests/engine.test.ts", TH.ENGINE_BASE)
        base = self.rebase_on("engine test")
        tests, protected = TH._old_inventory_globs()
        self.repo.write_active(base, test_globs=tests, protected_globs=protected)
        self.repo.write("tests/engine.test.ts",
                        TH.ENGINE_BASE.replace(TH.PILOT3_OLD, TH.PILOT3_NEW))
        for quick in (True, False):
            with self.subTest(quick=quick):
                report = self.guard(quick=quick)
                self.assertEqual(report.hard, [])
                self.assertIn({"file": "tests/engine.test.ts", "added_lines": 3},
                              report.info["strengthened_tests"])

    def test_config_under_a_test_glob_gaining_a_line_is_hard(self) -> None:
        self.repo.write("tests/vitest.config.ts", "export default {};\n")
        self.rebase_on("test runner config")
        self.repo.write("tests/vitest.config.ts", "export default {};\nexport const x = 1;\n")
