class RunPolicyTests(unittest.TestCase):
    """Allow lists (test deletions, config edits, lines), report-only mode, default globs."""

    def setUp(self) -> None:
        self.repo, self.base = make_repo()
        self.repo.write("package.json", '{\n  "name": "demo",\n  "scripts": {\n'
                                        '    "test": "vitest run"\n  },\n'
                                        '  "dependencies": {\n    "left-pad": "1.3.0"\n  }\n}\n')
        self.repo.write("pyproject.toml", "[tool.coverage.report]\nfail_under = 90\n")
        self.repo.write("tests/test_more.py", "def test_a():\n    assert 1\n\n\n"
                                              "def test_b():\n    assert 2\n")
        self.base = self.repo.commit("more")
        self.repo.write_active(self.base)

    def tearDown(self) -> None:
        self.repo.cleanup()

    def guard(self, quick: bool = False) -> dg.Report:
        return dg.run_guard(self.repo.path, self.base, dg.load_run_config(self.repo.path),
                            quick=quick)

    def test_default_protected_globs_cover_manifests_lockfiles_and_tool_configs(self) -> None:
        protected = dg.GlobSet(dg.DEFAULT_PROTECTED_GLOBS, ignore_case=False)
        for path in ("package.json", "web/package.json", "pyproject.toml", "Cargo.toml",
                     "go.mod", "foundry.toml", "pnpm-lock.yaml", "sub/Cargo.lock", "uv.lock",
                     ".flake8", ".pylintrc", ".coveragerc", "deny.toml", "codecov.yml",
                     "playwright.config.ts", ".solhint.json"):
            self.assertIsNotNone(protected.first_match(path), path)
        self.assertIsNone(protected.first_match("src/package.py"))

    def test_allowed_test_file_may_only_lose_lines(self) -> None:
        self.repo.write_active(self.base, allow_test_deletions=["tests/test_more.py"],
                               protected_globs=dg.DEFAULT_PROTECTED_GLOBS + ["tests/**"])
        self.repo.write("tests/test_more.py", "def test_a():\n    assert 1\n")
        for quick in (True, False):
            with self.subTest(quick=quick):
                report = self.guard(quick=quick)
                self.assertEqual(report.hard, [])
                self.assertEqual(report.info["allowed_test_changes"], ["tests/test_more.py"])
        self.repo.write("tests/test_more.py", "def test_a():\n    assert 1  # weakened\n")
        hard = self.guard(quick=True).hard
        self.assertEqual([(i["kind"], i["file"]) for i in hard],
                         [("test_modified", "tests/test_more.py")])
        self.assertIn("removes lines only", hard[0]["message"])
        self.repo.delete("tests/test_more.py")
