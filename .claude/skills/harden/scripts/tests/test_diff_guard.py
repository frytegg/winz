def setUpModule() -> None:
    """Isolate git from the user's global/system configuration."""
    global _GIT_HOME
    _GIT_HOME = tempfile.mkdtemp(prefix="harden-gitcfg-")
    cfg = Path(_GIT_HOME) / "gitconfig"
    cfg.write_text("[user]\n\tname = Harden Test\n\temail = harden@example.invalid\n"
                   "[init]\n\tdefaultBranch = main\n[commit]\n\tgpgsign = false\n"
                   "[core]\n\tautocrlf = false\n", encoding="utf-8")
    values = {"GIT_CONFIG_GLOBAL": str(cfg), "GIT_CONFIG_NOSYSTEM": "1",
              "GIT_AUTHOR_NAME": "Harden Test", "GIT_AUTHOR_EMAIL": "harden@example.invalid",
              "GIT_COMMITTER_NAME": "Harden Test", "GIT_COMMITTER_EMAIL": "harden@example.invalid"}
    for key, value in values.items():
        _SAVED_ENV[key] = os.environ.get(key)
        os.environ[key] = value


def tearDownModule() -> None:
    for key, value in _SAVED_ENV.items():
        if value is None:
            os.environ.pop(key, None)
        else:
            os.environ[key] = value
    if _GIT_HOME:
        _rmtree(_GIT_HOME)


def _rmtree(path: str) -> None:
    def fix(func, target, _exc):  # type: ignore[no-untyped-def]
        os.chmod(target, stat.S_IWRITE)
        func(target)
    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=fix)
    else:
        shutil.rmtree(path, onerror=fix)


class GitRepo:
    """A throw-away git repository."""

    def __init__(self) -> None:
        self.path = Path(tempfile.mkdtemp(prefix="harden-dg-"))
        self.git("init", "-q")

    def git(self, *args: str) -> str:
        proc = subprocess.run(["git", *args], cwd=str(self.path), stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, check=False)
        if proc.returncode != 0:
            raise RuntimeError(f"git {args} failed: {proc.stderr.decode(errors='replace')}")
        return proc.stdout.decode("utf-8", errors="replace")

    def write(self, rel: str, text: str) -> None:
        target = self.path / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")

    def delete(self, rel: str) -> None:
        (self.path / rel).unlink()

    def commit(self, message: str) -> str:
        self.git("add", "-A")
        self.git("commit", "-q", "-m", message)
        return self.git("rev-parse", "HEAD").strip()

    def write_active(self, base: str, **extra: object) -> None:
        data = {"base_sha": base, "branch": "main", "started": "2026-09-23T00:00:00Z",
                "mode": "apply", "protected_globs": [], "test_globs": [],
                "allow_test_deletions": []}
        data.update(extra)
        hdir = self.path / ".harden"
        hdir.mkdir(exist_ok=True)
        (hdir / "active").write_text(json.dumps(data), encoding="utf-8")
        exclude = self.path / ".git" / "info" / "exclude"
        exclude.parent.mkdir(parents=True, exist_ok=True)
        with open(exclude, "a", encoding="utf-8") as handle:
            handle.write("\n/.harden/\n")

    def cleanup(self) -> None:
        _rmtree(str(self.path))


def make_repo() -> Tuple[GitRepo, str]:
    repo = GitRepo()
    repo.write("src/app.py", "def add(a, b):\n    assert a is not None\n    if b is None:\n"
                             "        raise ValueError('b')\n    return a + b\n")
    repo.write("src/index.ts", "export function f(x: number): number {\n  return x;\n}\n"
                               "export const g = 1;\n")
    repo.write("src/lib.rs", "pub fn h() -> u32 {\n    1\n}\n")
    repo.write("src/pkg/__init__.py", "__all__ = ['a', 'b']\na = 1\nb = 2\n")
    repo.write("src/a.py", "x = 1  # noqa: E501\ny = 2\n")
    repo.write("tests/test_app.py", "from src.app import add\n\n\ndef test_add():\n"
                                    "    assert add(1, 2) == 3\n")
    repo.write("src/__snapshots__/view.snap", "exports[`a`] = `1`;\n")
    repo.write("tsconfig.json", '{"compilerOptions": {"strict": true}}\n')
    repo.write(".github/workflows/ci.yml", "on: push\n")
    repo.write("vendor/lib.js", "module.exports = 1;\n")
    repo.write("src/gen.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n")
    repo.write("README.md", "# demo\n")
    repo.write("Cargo.lock", "# This file is automatically @generated by Cargo.\nversion = 3\n")
    repo.write(".gitignore", "*.log\n")
    base = repo.commit("base")
    repo.write_active(base)
    return repo, base


def items(report: dg.Report, severity: str) -> Set[Tuple[str, str]]:
    source = report.hard if severity == "hard" else report.soft
    return {(i["kind"], i.get("file", "")) for i in source}


def kinds(report: dg.Report, severity: str) -> List[str]:
    source = report.hard if severity == "hard" else report.soft
    return [i["kind"] for i in source]


class DiffGuardTests(unittest.TestCase):
    def setUp(self) -> None:
        self.repo, self.base = make_repo()

    def tearDown(self) -> None:
        self.repo.cleanup()

    def guard(self, quick: bool = False, base: Optional[str] = None) -> dg.Report:
        cfg = dg.load_run_config(self.repo.path)
        return dg.run_guard(self.repo.path, base or self.base, cfg, quick=quick)

    def cli(self, *args: str) -> subprocess.CompletedProcess:
        return subprocess.run([sys.executable, str(SCRIPTS / "diff_guard.py"),
                               "--repo", str(self.repo.path), *args],
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)

    # -- tests and snapshots ---------------------------------------------

    def test_clean_tree_passes(self) -> None:
        report = self.guard()
        self.assertEqual(report.hard, [])
        self.assertEqual(report.soft, [])
        self.assertEqual(report.to_dict()["verdict"], "pass")

    def test_unstaged_test_modification_is_hard(self) -> None:
        self.repo.write("tests/test_app.py", "def test_add():\n    assert True\n")
        report = self.guard()
        self.assertIn(("test_modified", "tests/test_app.py"), items(report, "hard"))

    def test_staged_test_modification_is_hard(self) -> None:
        self.repo.write("tests/test_app.py", "def test_add():\n    pass\n")
        self.repo.git("add", "tests/test_app.py")
        self.assertIn(("test_modified", "tests/test_app.py"), items(self.guard(), "hard"))

    def test_committed_test_deletion_is_hard(self) -> None:
        self.repo.delete("tests/test_app.py")
        self.repo.commit("drop test")
        self.assertIn(("test_deleted", "tests/test_app.py"), items(self.guard(), "hard"))

    def test_snapshot_modification_is_hard(self) -> None:
        self.repo.write("src/__snapshots__/view.snap", "exports[`a`] = `2`;\n")
        self.assertIn(("test_modified", "src/__snapshots__/view.snap"),
                      items(self.guard(), "hard"))

    def test_allow_list_permits_listed_deletion_only(self) -> None:
        self.repo.write("tests/test_other.py", "def test_x():\n    assert 1\n")
        base = self.repo.commit("add second test")
        self.repo.write_active(base, allow_test_deletions=["tests/test_app.py"])
        self.repo.delete("tests/test_app.py")
        self.repo.delete("tests/test_other.py")
        report = self.guard(base=base)
        hard = items(report, "hard")
        self.assertNotIn(("test_deleted", "tests/test_app.py"), hard)
        self.assertIn(("test_deleted", "tests/test_other.py"), hard)
        self.assertIn("tests/test_app.py", report.info["allowed_test_changes"])

    def test_new_test_file_is_allowed(self) -> None:
        self.repo.write("tests/test_new.py", "def test_new():\n    assert 2 == 2\n")
        report = self.guard()
        self.assertEqual(report.hard, [])
        self.assertIn("tests/test_new.py", report.info["new_test_files"])

    # -- protected configs ---------------------------------------------------

    def test_protected_configs_are_hard(self) -> None:
        self.repo.write("tsconfig.json", '{"compilerOptions": {"strict": false}}\n')
        self.repo.write(".github/workflows/ci.yml", "on: push\njobs: {}\n")
        hard = items(self.guard(), "hard")
        self.assertIn(("protected_modified", "tsconfig.json"), hard)
        self.assertIn(("protected_modified", ".github/workflows/ci.yml"), hard)

    def test_new_protected_config_is_soft(self) -> None:
        self.repo.write("src/.eslintrc.json", '{"rules": {"no-console": "off"}}\n')
        report = self.guard()
        self.assertEqual(report.hard, [])
        self.assertIn(("protected_config_added", "src/.eslintrc.json"), items(report, "soft"))

    def test_globs_from_active_replace_defaults(self) -> None:
        self.repo.write("checks/check_x.py", "def check():\n    return 1\n")
        base = self.repo.commit("add checks")
        self.repo.write_active(base, test_globs=["checks/**"])
        self.repo.write("checks/check_x.py", "def check():\n    return 2\n")
        self.repo.write("tests/test_app.py", "def test_add():\n    assert True\n")
        hard = items(self.guard(base=base), "hard")
        self.assertIn(("test_modified", "checks/check_x.py"), hard)
        self.assertNotIn(("test_modified", "tests/test_app.py"), hard)

    # -- markers and suppressions --------------------------------------------

    def test_skip_markers_added_are_hard(self) -> None:
        self.repo.write("src/index.ts", "export function f(x: number): number {\n  return x;\n}\n"
                                        "export const g = 1;\nit.skip('later', () => {});\n")
        self.repo.write("src/lib.rs", "pub fn h() -> u32 {\n    1\n}\n#[ignore]\nfn slow() {}\n")
        self.repo.write("tests/test_new.py", "import pytest\n\n\n@pytest.mark.skip\n"
                                             "def test_new():\n    assert 1\n")
        report = self.guard()
        hard = items(report, "hard")
        self.assertIn(("marker_added", "src/index.ts"), hard)
        self.assertIn(("marker_added", "src/lib.rs"), hard)
        self.assertIn(("marker_added", "tests/test_new.py"), hard)

    def test_rust_iterator_skip_is_not_a_marker(self) -> None:
        self.repo.write("src/lib.rs", "pub fn h() -> u32 {\n    1\n}\nfn tail(xs: &[u8]) -> "
                                      "Vec<u8> {\n    xs.iter().skip(1).cloned().collect()\n}\n")
        self.assertNotIn("marker_added", kinds(self.guard(), "hard"))

    def test_suppressions_added_are_hard(self) -> None:
        self.repo.write("src/app.py", "def add(a, b):\n    assert a is not None\n    if b is None:\n"
                                      "        raise ValueError('b')\n"
                                      "    return a + b  # type: ignore\n")
        self.repo.write("src/index.ts", "// eslint-disable-next-line no-console\n"
                                        "export function f(x: number): number {\n"
                                        "  return x as any;\n}\nexport const g = 1;\n")
        self.repo.write("src/lib.rs", "#[allow(dead_code)]\npub fn h() -> u32 {\n    1\n}\n")
        report = self.guard()
        sups = [(i["file"], i["pattern"]) for i in report.hard if i["kind"] == "suppression_added"]
        self.assertIn(("src/app.py", "type-ignore"), sups)
        self.assertIn(("src/index.ts", "eslint-disable"), sups)
        self.assertIn(("src/index.ts", "as-any"), sups)
        self.assertIn(("src/lib.rs", "rust-allow"), sups)

    def test_moved_suppression_is_not_new(self) -> None:
        self.repo.write("src/a.py", "y = 2\n")
        self.repo.write("src/b.py", "x = 1  # noqa: E501\n")
        self.assertNotIn("suppression_added", kinds(self.guard(), "hard"))

    def test_english_as_any_is_not_a_suppression(self) -> None:
        self.repo.write("src/index.ts", "export function f(x: number): number {\n"
                                        "  // behaves as any other function\n  return x;\n}\n"
                                        "export const g = 1;\n")
        self.repo.write("src/notes.py", "# accepts input as any other caller would\n")
        self.assertNotIn("suppression_added", kinds(self.guard(), "hard"))

    def test_suppression_in_docs_is_soft(self) -> None:
        self.repo.write("README.md", "# demo\n\nAvoid `# noqa` and `it.skip(` here.\n")
        report = self.guard()
        self.assertEqual(report.hard, [])
        soft = kinds(report, "soft")
        self.assertIn("suppression_in_docs", soft)
        self.assertIn("marker_in_docs", soft)

    def test_ignored_files_are_not_scanned(self) -> None:
        self.repo.write("debug.log", "x = 1  # noqa\n")
        self.assertEqual(self.guard().hard, [])

    # -- history, base, generated -------------------------------------------

    def test_history_rewrite_is_hard(self) -> None:
        self.repo.write("src/extra.py", "z = 3\n")
        second = self.repo.commit("second")
        self.repo.git("reset", "-q", "--hard", self.base)
        self.repo.write("src/other.py", "w = 4\n")
        self.repo.commit("diverge")
        report = self.guard(base=second)
        self.assertIn("history_rewritten", kinds(report, "hard"))

    def test_missing_base_is_hard(self) -> None:
        report = self.guard(base="0" * 40)
        self.assertEqual(kinds(report, "hard"), ["base_not_found"])

    def test_generated_and_vendor_files_are_hard(self) -> None:
        self.repo.write("vendor/lib.js", "module.exports = 2;\n")
        self.repo.write("src/gen.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n"
                                      "package gen\n\nvar X = 1\n")
        for quick in (True, False):
            hard = items(self.guard(quick=quick), "hard")
            self.assertIn(("generated_touched", "vendor/lib.js"), hard)
            self.assertIn(("generated_touched", "src/gen.go"), hard)

    def test_lockfile_change_is_protected_not_generated(self) -> None:
        # Invariant 2: lockfiles are read-only unless run_state.py allow-config-edit records
        # them; the @generated header does not make them "generated_touched".
        self.repo.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n"
                                      "version = 4\n")
        report = self.guard()
        self.assertEqual(items(report, "hard"), {("protected_modified", "Cargo.lock")})
        self.repo.write_active(self.base, allow_config_edits=["Cargo.lock"])
        report = self.guard()
        self.assertEqual(report.hard, [])
        self.assertEqual(report.info["allowed_config_edits"], ["Cargo.lock"])
        self.assertIn(("lockfile_changed", "Cargo.lock"), items(report, "soft"))

    # -- soft content checks --------------------------------------------------

    def test_removed_guards_are_soft(self) -> None:
        self.repo.write("src/app.py", "def add(a, b):\n    return a + b\n")
        report = self.guard()
        guards = [i for i in report.soft if i["kind"] == "removed_guard_lines"]
        self.assertEqual(len(guards), 1)
        self.assertEqual(guards[0]["count"], 2)
        whats = {e["what"] for e in guards[0]["examples"]}
        self.assertIn("assert", whats)
        self.assertIn("throw/raise in if-block", whats)

    def test_session_referential_comment_is_soft(self) -> None:
        self.repo.write("src/app.py", "def add(a, b):\n    assert a is not None\n    if b is None:\n"
                                      "        raise ValueError('b')\n"
                                      "    # now uses plain addition instead of the old loop\n"
                                      "    return a + b\n")
        self.assertIn(("session_referential_comment", "src/app.py"),
                      items(self.guard(), "soft"))

    def test_public_api_removal_is_soft(self) -> None:
        self.repo.write("src/index.ts", "export function f(x: number): number {\n  return x;\n}\n")
        self.repo.write("src/lib.rs", "fn h() -> u32 {\n    1\n}\n")
        self.repo.write("src/pkg/__init__.py", "__all__ = ['a']\na = 1\nb = 2\n")
        api = [i for i in self.guard().soft if i["kind"] == "public_api_removed"]
        files = {i["file"] for i in api}
        self.assertEqual(files, {"src/index.ts", "src/lib.rs", "src/pkg/__init__.py"})
        names = [i for i in api if i["file"] == "src/pkg/__init__.py"][0]["names"]
        self.assertEqual(names, ["b"])

    def test_quick_mode_is_file_level_and_fast(self) -> None:
        self.repo.write("src/app.py", "def add(a, b):  # type: ignore\n    return a + b\n")
        self.repo.write("tests/test_app.py", "def test_add():\n    assert True\n")
        start = time.perf_counter()
        quick = self.guard(quick=True)
        elapsed = time.perf_counter() - start
        self.assertLess(elapsed, 1.0, f"quick mode took {elapsed:.2f}s")
        self.assertEqual(kinds(quick, "hard"), ["test_modified", "suppression_added"])
        full_kinds = kinds(self.guard(), "hard")
        self.assertIn("test_modified", full_kinds)
        self.assertIn("suppression_added", full_kinds)

    def test_quick_mode_reports_new_suppressions_and_markers(self) -> None:
        # The per-item check (protocol-change step 8) runs --quick: a new `# noqa` and a new
        # xfail marker in a new test file must fail it exactly as they fail the full run.
        self.repo.write("src/app.py", "def add(a, b):\n    assert a is not None\n    if b is None:\n"
                                      "        raise ValueError('b')\n"
                                      "    f = lambda: a + b  # noqa: E731\n    return f()\n")
        self.repo.write("tests/test_new.py", "import pytest\n\n\n@pytest.mark.xfail\n"
                                             "def test_new():\n    assert 0\n")
        self.repo.write("src/index.ts", "// eslint-disable-next-line\nexport function f(x: number)"
                                        ": number {\n  return x;\n}\nexport const g = 1;\n")
        for quick in (True, False):
            with self.subTest(quick=quick):
                hard = {(i["kind"], i["file"], i.get("pattern")) for i in
                        self.guard(quick=quick).hard}
                self.assertIn(("suppression_added", "src/app.py", "noqa"), hard)
                self.assertIn(("marker_added", "tests/test_new.py", "pytest-mark-skip"), hard)
                self.assertIn(("suppression_added", "src/index.ts", "eslint-disable"), hard)
        quick = self.guard(quick=True)
        self.assertGreater(quick.info["quick_markers"]["added_lines_scanned"], 0)

    def test_quick_marker_scan_line_cap(self) -> None:
        self.repo.write("src/big.py", "x = 1\n" * 30 + "y = 2  # noqa\n")
        with mock.patch.object(dg, "QUICK_GAMING_LINE_CAP", 10):
            quick = self.guard(quick=True)
        self.assertTrue(quick.info["quick_markers"]["truncated"])
        self.assertNotIn("suppression_added", kinds(quick, "hard"))
        self.assertIn("suppression_added", kinds(self.guard(), "hard"))

