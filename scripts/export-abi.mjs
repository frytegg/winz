// Regenerates packages/shared/src/abi/winz-escrow.ts from the compiled IWinzEscrow interface.
// Run after any change to the interface: `pnpm --filter @winz/contracts build && node scripts/export-abi.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = resolve(root, "packages/contracts/out/IWinzEscrow.sol/IWinzEscrow.json");
const outputPath = resolve(root, "packages/shared/src/abi/winz-escrow.ts");

const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
const abi = JSON.stringify(artifact.abi, null, 2);

writeFileSync(
  outputPath,
  `// Generated by scripts/export-abi.mjs from packages/contracts/src/interfaces/IWinzEscrow.sol. Do not edit.\n` +
    `export const winzEscrowAbi = ${abi} as const;\n`,
);
console.log(`Wrote ${artifact.abi.length} ABI entries to ${outputPath}`);
