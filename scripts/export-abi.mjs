// Exports what TypeScript needs from the compiled contracts, from packages/contracts/out:
// - packages/shared/src/abi/winz-escrow.ts: the ABI of the WinzEscrow IMPLEMENTATION as
//   `winzEscrowAbi`. It is a superset of IWinzEscrow (setRoles, Ownable, the EIP-712 view and the
//   OpenZeppelin custom errors), so the engine can decode every revert the contract can raise.
// - packages/contracts/artifacts/{WinzEscrow,TestUSDC}.json: { abi, bytecode }, so TypeScript tests
//   deploy the contracts without running forge. The bytecode is reproducible (foundry.toml sets
//   bytecode_hash = "none" and cbor_metadata = false).
//
// Usage, from the repository root:
//   pnpm --filter @winz/contracts build && node scripts/export-abi.mjs     regenerate the files
//   node scripts/export-abi.mjs --check     compare the committed files with packages/contracts/out
//                                           (writes nothing; exits 1 on drift, 2 if out/ is missing)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contractsDir = resolve(root, "packages/contracts");
const outDir = resolve(contractsDir, "out");

/** Compiled contracts whose { abi, bytecode } are committed under packages/contracts/artifacts. */
const ARTIFACTS = [
  { contract: "WinzEscrow", source: "WinzEscrow.sol" },
  { contract: "TestUSDC", source: "TestUSDC.sol" },
];

const ABI_TS_PATH = resolve(root, "packages/shared/src/abi/winz-escrow.ts");
const ABI_TS_HEADER =
  "// Generated by scripts/export-abi.mjs from packages/contracts/src/WinzEscrow.sol (the implementation:\n" +
  "// IWinzEscrow plus setRoles, Ownable, the EIP-712 view and the OpenZeppelin errors). Do not edit.\n";

class ExportError extends Error {
  constructor(message, exitCode) {
    super(message);
    this.name = "ExportError";
    this.exitCode = exitCode;
  }
}

function readCompiled({ contract, source }) {
  const path = resolve(outDir, source, `${contract}.json`);
  if (!existsSync(path)) {
    throw new ExportError(
      `${relative(root, path)} not found: build the contracts first (pnpm --filter @winz/contracts build).`,
      2,
    );
  }
  const compiled = JSON.parse(readFileSync(path, "utf8"));
  const bytecode = compiled.bytecode?.object;
  if (
    !Array.isArray(compiled.abi) ||
    typeof bytecode !== "string" ||
    !/^0x[0-9a-f]+$/i.test(bytecode)
  ) {
    throw new ExportError(`${relative(root, path)} has no ABI or no bytecode.`, 2);
  }
  return { abi: compiled.abi, bytecode };
}

/** Every file this script owns, path → expected content. */
function expectedFiles() {
  const files = new Map();
  for (const entry of ARTIFACTS) {
    const { abi, bytecode } = readCompiled(entry);
    files.set(
      resolve(contractsDir, "artifacts", `${entry.contract}.json`),
      `${JSON.stringify({ abi, bytecode }, null, 2)}\n`,
    );
    if (entry.contract === "WinzEscrow") {
      files.set(
        ABI_TS_PATH,
        `${ABI_TS_HEADER}export const winzEscrowAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
      );
    }
  }
  return files;
}

// ------------------------------------------------------------------------------------------------
// Drift report
// ------------------------------------------------------------------------------------------------

function signature(entry) {
  const types = (params) =>
    (params ?? [])
      .map((param) =>
        param.type.startsWith("tuple")
          ? `(${types(param.components)})${param.type.slice("tuple".length)}`
          : param.type,
      )
      .join(",");
  return `${entry.type} ${entry.name ?? ""}(${types(entry.inputs)})`;
}

/** The ABI held by a committed file, or undefined when it cannot be read. */
function abiOf(path, content) {
  try {
    if (path.endsWith(".json")) return JSON.parse(content).abi;
    const match = /=\s*(\[[\s\S]*\])\s*as const;/.exec(content);
    return match ? JSON.parse(match[1]) : undefined;
  } catch {
    return undefined;
  }
}

function describeAbiDrift(committedAbi, expectedAbi) {
  if (!Array.isArray(committedAbi)) return ["  committed ABI cannot be parsed"];
  const lines = [];
  const committed = new Map(committedAbi.map((entry) => [signature(entry), entry]));
  const expected = new Map(expectedAbi.map((entry) => [signature(entry), entry]));
  for (const [sig, entry] of expected) {
    if (!committed.has(sig)) lines.push(`  + ${sig}  (in out/, not committed)`);
    else if (JSON.stringify(committed.get(sig)) !== JSON.stringify(entry)) {
      lines.push(`  ~ ${sig}  (names, mutability or indexing differ)`);
    }
  }
  for (const sig of committed.keys()) {
    if (!expected.has(sig)) lines.push(`  - ${sig}  (committed, no longer in out/)`);
  }
  if (lines.length === 0 && JSON.stringify(committedAbi) !== JSON.stringify(expectedAbi)) {
    lines.push("  same entries, different order");
  }
  return lines;
}

function describeBytecodeDrift(committed, expected) {
  if (typeof committed !== "string") return ["  committed bytecode missing"];
  if (committed === expected) return [];
  let index = 0;
  while (index < committed.length && committed[index] === expected[index]) index += 1;
  const byteOffset = Math.max(0, Math.floor((index - 2) / 2));
  return [
    `  bytecode differs: committed ${String((committed.length - 2) / 2)} bytes, out/ ${String(
      (expected.length - 2) / 2,
    )} bytes, first difference at byte ${String(byteOffset)}`,
  ];
}

function describeDrift(path, committed, expected) {
  const lines = [];
  const expectedAbi = abiOf(path, expected);
  const abiLines = describeAbiDrift(abiOf(path, committed), expectedAbi);
  lines.push(...abiLines);
  if (path.endsWith(".json")) {
    let committedBytecode;
    try {
      committedBytecode = JSON.parse(committed).bytecode;
    } catch {
      committedBytecode = undefined;
    }
    lines.push(...describeBytecodeDrift(committedBytecode, JSON.parse(expected).bytecode));
  }
  if (lines.length === 0) lines.push("  same content, different formatting or header");
  return lines;
}

// ------------------------------------------------------------------------------------------------
// Main
// ------------------------------------------------------------------------------------------------

function check(files) {
  const report = [];
  for (const [path, expected] of files) {
    const name = relative(root, path);
    if (!existsSync(path)) {
      report.push(`${name}: missing`);
      continue;
    }
    const committed = readFileSync(path, "utf8");
    if (committed !== expected)
      report.push(`${name}: out of date`, ...describeDrift(path, committed, expected));
  }
  if (report.length > 0) {
    console.error("Committed ABI and artifacts differ from packages/contracts/out:");
    for (const line of report) console.error(line);
    console.error(
      "Regenerate with `pnpm --filter @winz/contracts build && node scripts/export-abi.mjs`, then commit.",
    );
    return 1;
  }
  console.log(`ABI and artifacts are up to date (${String(files.size)} files).`);
  return 0;
}

function write(files) {
  for (const [path, content] of files) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`Wrote ${relative(root, path)}`);
  }
  return 0;
}

const args = process.argv.slice(2);
const unknown = args.filter((arg) => arg !== "--check");
if (unknown.length > 0) {
  console.error(
    `Unknown argument(s): ${unknown.join(" ")}. Usage: node scripts/export-abi.mjs [--check]`,
  );
  process.exit(2);
}

try {
  const files = expectedFiles();
  process.exit(args.includes("--check") ? check(files) : write(files));
} catch (error) {
  if (error instanceof ExportError) {
    console.error(error.message);
    process.exit(error.exitCode);
  }
  throw error;
}
